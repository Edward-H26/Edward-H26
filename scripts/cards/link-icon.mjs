/**
 * @param {import("../svg.mjs").Theme} theme
 * @param {import("../data/links.mjs").Link} link
 */
export function renderLinkIcon(theme, link) {
  const dark = theme.name === "dark"
  const id = `link-${link.id}`
  const center = SIZE / 2
  const body = [
    `<circle cx="${center}" cy="${center}" r="${RADIUS}" fill="${dark ? "#f7e3c9" : "#fdefd9"}"/>`,
    `<g clip-path="url(#${id}-clip)"><rect x="-70" y="0" width="34" height="${SIZE}" fill="url(#${id}-shine)" transform="skewX(-22)"><animate attributeName="x" from="-70" to="110" dur="${SHEEN_SECONDS}s" begin="${LINKS.indexOf(link) * SHEEN_STAGGER_SECONDS}s" repeatCount="indefinite"/></rect></g>`,
    `<g transform="translate(${center} ${center}) scale(1.17) translate(-12 -12)" fill="#3d4a5c"><path d="${LINK_ICONS[link.icon]}"/></g>`
  ].join("")
  const defs = [
    `<clipPath id="${id}-clip"><circle cx="${center}" cy="${center}" r="${RADIUS}"/></clipPath>`,
    linearGradient(`${id}-shine`, [
      ["0", "#ffffff", 0],
      ["0.5", "#ffffff", 0.7],
      ["1", "#ffffff", 0]
    ])
  ].join("")
  return svgDocument({ id, width: SIZE, height: SIZE, title: link.label, theme, defs, body, background: false })
}
